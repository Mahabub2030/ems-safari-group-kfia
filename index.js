      function applyFilters() {
        const query = document
          .getElementById("tableSearch")
          .value.toLowerCase()
          .trim();
        const selectedGroup = document.getElementById("groupFilter").value;

        filteredData = employeesData.filter((emp) => {
          let matchesCard = true;
          if (currentCardFilter === "vacation")
            matchesCard = emp.status === "On Vacation";
          else if (currentCardFilter === "saudi")
            matchesCard = emp.nationality === "Saudi";
          else if (currentCardFilter === "bd")
            matchesCard = emp.nationality === "Bangladeshi";

          let matchesGroup = true;
          if (selectedGroup !== "all") {
            matchesGroup = emp.group === selectedGroup || emp.dept === selectedGroup;
          }

          const matchesQuery =
            emp.name.toLowerCase().includes(query) ||
            emp.id.toLowerCase().includes(query) ||
            emp.role.toLowerCase().includes(query) ||
            emp.dept.toLowerCase().includes(query) ||
            (emp.group && emp.group.toLowerCase().includes(query)) ||
            emp.nationality.toLowerCase().includes(query) ||
            (emp.iqamaNo && emp.iqamaNo.toLowerCase().includes(query)) ||
            (emp.dmmId && emp.dmmId.toLowerCase().includes(query));

          return matchesCard && matchesGroup && matchesQuery;
        });

        currentPage = 1;
        renderEmployeeTable();
      }

