      // --- EXPORT FUNCTIONS ---
      function exportToExcel(type) {
        const dataToExport = type === "iqama" ? filteredIqamaData : filteredData;
        const worksheet = XLSX.utils.json_to_sheet(dataToExport);
        const workbook = XLSX.utils.book_new();
        XLSX.utils.book_append_sheet(workbook, worksheet, "Data");
        XLSX.writeFile(workbook, `ProEMS_${type}_export.xlsx`);
      }

      function exportToPDF(type) {
        const { jsPDF } = window.jspdf;
        const doc = new jsPDF();
        doc.text(`ProEMS ${type.toUpperCase()} Export`, 14, 15);

        const data = type === "iqama" ? filteredIqamaData : filteredData;
        const headers = type === "iqama"
          ? [["ID", "Name", "Iqama No", "Iqama Exp", "DMM ID", "DMM Exp"]]
          : [["ID", "Name", "Role", "Group", "Iqama No", "DMM ID"]];

        const rows = data.map((e) =>
          type === "iqama"
            ? [e.id, e.name, e.iqamaNo, e.expiryDate, e.dmmId, e.dmmExpiryDate]
            : [e.id, e.name, e.role, e.group || e.dept, e.iqamaNo, e.dmmId]
        );

        doc.autoTable({
          head: headers,
          body: rows,
          startY: 20
        });

        doc.save(`ProEMS_${type}_export.pdf`);
      }

