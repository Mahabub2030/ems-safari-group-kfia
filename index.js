      function onIqamaSearchInput() {
        applyIqamaFilters();
      }

      function applyIqamaFilters() {
        const query = document
          .getElementById("iqamaSearch")
          .value.toLowerCase()
          .trim();

        filteredIqamaData = employeesData.filter((emp) => {
          const daysLeft = calculateDaysRemaining(emp.expiryDate);
          const dmmDaysLeft = calculateDaysRemaining(emp.dmmExpiryDate);
          let matchesCard = true;

          if (iqamaCardFilter === "soon")
            matchesCard = daysLeft !== null && daysLeft >= 0 && daysLeft <= 30;
          else if (iqamaCardFilter === "expired")
            matchesCard = daysLeft !== null && daysLeft < 0;
          else if (iqamaCardFilter === "dmm-expired")
            matchesCard = dmmDaysLeft !== null && dmmDaysLeft < 0;

          const matchesQuery =
            emp.name.toLowerCase().includes(query) ||
            emp.iqamaNo.toLowerCase().includes(query) ||
            emp.dmmId.toLowerCase().includes(query);

          return matchesCard && matchesQuery;
        });

        iqamaCurrentPage = 1;
        renderIqamaTable();
      }

      function onIqamaPageSizeChange() {
        const val = document.getElementById("iqamaPageSize").value;
        iqamaPageSize = val === "all" ? filteredIqamaData.length : parseInt(val, 10);
        iqamaCurrentPage = 1;
        renderIqamaTable();
      }

      function renderIqamaTable() {
        const tbody = document.getElementById("iqamaTableBody");
        tbody.innerHTML = "";

        const totalEntries = filteredIqamaData.length;
        const effectivePageSize = iqamaPageSize === 0 ? totalEntries : iqamaPageSize;
        const totalPages = Math.ceil(totalEntries / effectivePageSize) || 1;

        if (iqamaCurrentPage > totalPages) iqamaCurrentPage = totalPages;

        const startIdx = (iqamaCurrentPage - 1) * effectivePageSize;
        const endIdx = Math.min(startIdx + effectivePageSize, totalEntries);
        const pageData = filteredIqamaData.slice(startIdx, endIdx);

        if (pageData.length === 0) {
          tbody.innerHTML = `<tr><td colspan="9" class="text-center py-6 text-gray-400">No matching documents found</td></tr>`;
        } else {
          pageData.forEach((emp, index) => {
            const daysLeft = calculateDaysRemaining(emp.expiryDate);
            const dmmDaysLeft = calculateDaysRemaining(emp.dmmExpiryDate);

            let statusBadge = `<span class="bg-emerald-100 text-emerald-800 px-2 py-0.5 rounded-full text-xs font-semibold">Valid</span>`;
            if (daysLeft !== null && daysLeft < 0) {
              statusBadge = `<span class="bg-red-100 text-red-800 px-2 py-0.5 rounded-full text-xs font-semibold">Expired</span>`;
            } else if (daysLeft !== null && daysLeft <= 30) {
              statusBadge = `<span class="bg-amber-100 text-amber-800 px-2 py-0.5 rounded-full text-xs font-semibold">Expiring Soon</span>`;
            }

            let dmmStatusBadge = `<span class="bg-emerald-100 text-emerald-800 px-2 py-0.5 rounded-full text-xs font-semibold">Active</span>`;
            if (dmmDaysLeft !== null && dmmDaysLeft < 0) {
              dmmStatusBadge = `<span class="bg-rose-100 text-rose-800 px-2 py-0.5 rounded-full text-xs font-semibold">Expired</span>`;
            }

            const row = document.createElement("tr");
            row.className = "hover:bg-gray-50 transition";
            row.innerHTML = `
              <td class="px-3 py-3.5 text-center font-medium text-gray-500">${startIdx + index + 1}</td>
              <td class="px-4 py-3.5">
                <div class="font-bold text-gray-900">${emp.name}</div>
                <div class="text-xs text-gray-400">ID: ${emp.id}</div>
              </td>
              <td class="px-4 py-3.5 font-mono font-semibold">${emp.iqamaNo}</td>
              <td class="px-4 py-3.5 text-xs">
                <div><strong>Iss:</strong> ${emp.issueDate || "-"}</div>
                <div><strong>Exp:</strong> ${emp.expiryDate || "-"}</div>
              </td>
              <td class="px-4 py-3.5">${statusBadge}</td>
              <td class="px-4 py-3.5 font-mono">${emp.dmmId}</td>
              <td class="px-4 py-3.5 text-xs">
                <div><strong>Iss:</strong> ${emp.dmmIssueDate || "-"}</div>
                <div><strong>Exp:</strong> ${emp.dmmExpiryDate || "-"}</div>
              </td>
              <td class="px-4 py-3.5">${dmmStatusBadge}</td>
              <td class="px-4 py-3.5"><span class="text-xs font-medium bg-slate-100 text-slate-700 px-2 py-1 rounded">${emp.vacationStatus}</span></td>
            `;
            tbody.appendChild(row);
          });
        }

        document.getElementById("iqamaPaginationInfo").innerText =
          totalEntries === 0
            ? "Showing 0 to 0 of 0 entries"
            : `Showing ${startIdx + 1} to ${endIdx} of ${totalEntries} entries`;
      }

